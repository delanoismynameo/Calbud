// codemap.mjs: rewrites the generated half of CODEMAP.md, which lists every
// source file with what it exports, so a coding agent can find code without
// grepping. The hand-written half (above the marker) is kept as it is.
//
// Usage: node scripts/codemap.mjs          (rewrite CODEMAP.md)
//        node scripts/codemap.mjs --check  (exit 1 if CODEMAP.md is out of date)

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, relative, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const mapPath = join(root, 'CODEMAP.md')
const MARKER = '<!-- Everything below is generated by `node scripts/codemap.mjs`. Do not edit it by hand. -->'

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('__') || entry.name === 'node_modules') continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else out.push(full)
  }
  return out
}

// Exported names, values first, then types. Regex-based: good enough for this
// codebase, which uses plain `export function/const/interface/type` forms.
function exportsOf(text) {
  const values = []
  const types = []
  const add = (list, name) => { if (name && !list.includes(name)) list.push(name) }
  for (const m of text.matchAll(/^export\s+default\s+(?:async\s+)?function\s*\*?\s*(\w+)?/gm)) {
    add(values, m[1] ? `${m[1]} (default)` : '(default)')
  }
  for (const m of text.matchAll(/^export\s+(?:async\s+)?(?:function\s*\*?|const|let|class)\s+(\w+)/gm)) add(values, m[1])
  for (const m of text.matchAll(/^export\s+(?:interface|type|enum)\s+(\w+)/gm)) add(types, m[1])
  for (const m of text.matchAll(/^export\s+(type\s+)?\{([^}]*)\}/gm)) {
    for (const part of m[2].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop()?.replace(/^type\s+/, '')
      if (name) add(m[1] || /^\s*type\s/.test(part) ? types : values, name)
    }
  }
  return { values, types }
}

// The file's own first comment line, when it starts with one (after imports).
function firstComment(text) {
  const parts = []
  for (const line of text.split('\n')) {
    const t = line.trim()
    if (parts.length === 0 && (t === '' || t.startsWith('import ') || t.startsWith('///'))) continue
    const m = t.match(/^\/\/\s*(.*)/)
    if (!m) break
    parts.push(m[1])
  }
  const note = parts.join(' ').replace(/\s+/g, ' ').trim()
  if (!note) return null
  return note.length > 140 ? note.slice(0, 140).replace(/\s+\S*$/, '') + '…' : note
}

function generate() {
  const srcDir = join(root, 'src')
  const files = walk(srcDir).filter((f) => /\.(ts|tsx)$/.test(f) && !f.endsWith('.d.ts')).sort()
  const tested = new Set(files.filter((f) => /\.test\.tsx?$/.test(f)).map((f) => f.replace(/\.test(\.tsx?)$/, '$1')))
  const byDir = new Map()
  for (const f of files) {
    if (/\.test\.tsx?$/.test(f)) continue
    const dir = relative(root, dirname(f)).replace(/\\/g, '/')
    if (!byDir.has(dir)) byDir.set(dir, [])
    byDir.get(dir).push(f)
  }

  const lines = ['## Source files', '', '`(tested)` means a `.test.ts` sits next to the file. Types are listed after `types:`.', '']
  for (const [dir, list] of byDir) {
    lines.push(`### ${dir}/`)
    for (const f of list) {
      const text = readFileSync(f, 'utf8')
      const { values, types } = exportsOf(text)
      const name = relative(join(root, dir), f).replace(/\\/g, '/')
      const parts = []
      if (values.length) parts.push(values.join(', '))
      if (types.length) parts.push(`types: ${types.join(', ')}`)
      const note = firstComment(text)
      let line = `- \`${name}\`${tested.has(f) ? ' (tested)' : ''}`
      if (parts.length) line += `: ${parts.join('; ')}`
      if (note) line += `. _${note}_`
      lines.push(line)
    }
    lines.push('')
  }

  const migDir = join(root, 'supabase', 'migrations')
  if (existsSync(migDir)) {
    lines.push('## Migrations (`supabase/migrations/`, applied in name order)', '')
    for (const m of readdirSync(migDir).filter((n) => n.endsWith('.sql')).sort()) lines.push(`- \`${m}\``)
    lines.push('')
  }
  return lines.join('\n')
}

// Each target keeps everything up to its marker and gets the generated map after it.
// AGENTS.md (local only, loaded into every harness session) is optional; CODEMAP.md is not.
const generated = generate()
const agentsPath = join(root, 'AGENTS.md')
const targets = [{ path: mapPath, name: 'CODEMAP.md', required: true }, { path: agentsPath, name: 'AGENTS.md', required: false }]
let stale = false
for (const { path, name, required } of targets) {
  if (!existsSync(path)) {
    if (required) { console.error(`${name} is missing.`); process.exit(1) }
    continue
  }
  const current = readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
  const at = current.indexOf(MARKER)
  if (at < 0) {
    if (required) { console.error(`${name} has no generated-section marker; add it at the end of the hand-written part.`); process.exit(1) }
    continue
  }
  const next = current.slice(0, at + MARKER.length) + '\n\n' + generated
  if (process.argv.includes('--check')) {
    if (next !== current) { console.error(`${name} is out of date. Run: node scripts/codemap.mjs`); stale = true }
    else console.log(`${name} is up to date.`)
  } else {
    writeFileSync(path, next)
    console.log(`${name} written (${Buffer.byteLength(next)} bytes).`)
  }
}
if (stale) process.exit(1)
